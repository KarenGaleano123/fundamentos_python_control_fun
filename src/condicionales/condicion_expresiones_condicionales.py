# Uso de if-else tradicional

# Se evalúa una condición
if condición:
    # Si la condición es verdadera, se asigna este valor
    variable = valor_verdadero
else:
    # Si la condición es falsa, se asigna este otro valor
    variable = valor_falso


# Uso de expresión condicional (operador ternario)

# Se asigna el valor directamente en una sola línea:
# - valor_verdadero si la condición se cumple
# - valor_falso si no se cumple
variable = valor_verdadero if condición else valor_falso