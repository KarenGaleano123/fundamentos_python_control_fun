# Se crea una variable llamada 'edad' y se le asigna el valor 17
edad = 17

# Se verifica si la edad es mayor o igual a 18
if edad >= 18:
    # Si la condición se cumple, se muestra el mensaje indicando que puede votar
    print("Puedes votar en las elecciones.")
else:
    # Si la condición NO se cumple, se muestra el mensaje indicando que no puede votar
    print("Aún no tienes edad para votar.")