# Se crea una variable llamada 'numero' y se le asigna el valor 0
numero = 0

# Se verifica si el número es mayor que 0
if numero > 0:
    # Si se cumple, el número es positivo
    print("El número es positivo.")

# Si no es positivo, se verifica si es menor que 0
elif numero < 0:
    # Si se cumple, el número es negativo
    print("El número es negativo.")

# Si no cumple ninguna de las condiciones anteriores
else:
    # Significa que el número es exactamente 0
    print("El número es cero.")