# Se crea una variable llamada 'edad' y se le asigna el valor 17
edad = 17

# Se utiliza un operador ternario (if en una sola línea)
# Si edad es mayor o igual a 18 → asigna "Eres mayor de edad."
# Si no se cumple → asigna "Eres menor de edad."
mensaje = "Eres mayor de edad." if edad >= 18 else "Eres menor de edad."

# Se imprime el resultado almacenado en la variable 'mensaje'
print(mensaje)