# Se crea una variable llamada 'numero' y se le asigna el valor 15
numero = 15

# Se verifica si el número es divisible entre 2 usando el operador módulo (%)
# Si el residuo de la división es 0, el número es par
if numero % 2 == 0:
    # Si se cumple la condición, se indica que el número es par
    print("El número es par.")
else:
    # Si no se cumple, significa que el número es impar
    print("El número es impar.")