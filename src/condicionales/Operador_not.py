# Se crea una variable llamada 'llueve' y se le asigna el valor False (no está lloviendo)
llueve = False

# Se evalúa la condición usando el operador 'not' (negación)
# 'not llueve' significa que se verifica si NO está lloviendo
if not llueve:
    # Si no está lloviendo, se muestra el mensaje
    print("Podemos salir al parque.")