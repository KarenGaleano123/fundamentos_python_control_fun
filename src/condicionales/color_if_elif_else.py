# Se crea una variable llamada 'color' y se le asigna el valor "azul"
color = "azul"

# Se verifica si el color es "rojo"
if color == "rojo":
    # Si se cumple, se imprime este mensaje
    print("El color es rojo.")

# Si no fue rojo, se verifica si es "verde"
elif color == "verde":
    # Si se cumple, se imprime este mensaje
    print("El color es verde.")

# Si no fue ninguno de los anteriores, se verifica si es "azul"
elif color == "azul":
    # Si se cumple, se imprime este mensaje
    print("El color es azul.")