# Se crean dos variables: 'edad' e 'ingresos'
edad = 25          # Edad de la persona
ingresos = 30000   # Ingresos de la persona

# Se verifica si cumple ambas condiciones:
# 1. Ser mayor o igual a 18 años
# 2. Tener ingresos mayores o iguales a 20000
if edad >= 18 and ingresos >= 20000:
    # Si ambas condiciones se cumplen, se muestra el mensaje
    print("Eres elegible para el crédito.")